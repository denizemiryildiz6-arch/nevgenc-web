-- -----------------------------------------------------------------------------
-- 3) Supabase Before User Created Hook
-- Dashboard > Authentication > Hooks bölümünde private.hook_restrict_signup seçilmelidir.
-- İzinli ise {} döner; aksi durumda kayıt Auth tablosuna hiç yazılmaz.
-- -----------------------------------------------------------------------------
create or replace function private.hook_restrict_signup(event jsonb)
returns jsonb
language plpgsql stable security definer set search_path=''
as $$
declare v_email text;
begin
  v_email:=lower(coalesce(event->'user'->>'email',''));
  if v_email ~ '^[^@[:space:]]+@ogr\.sakarya\.edu\.tr$'
     or v_email ~ '^g[0-9]+@subu\.edu\.tr$'
     or v_email ~ '^[^@[:space:]]+@(sakarya\.edu\.tr|serdivan\.bel\.tr)$'
     or exists(select 1 from public.auth_signup_allowlist a where a.email=v_email) then
    return '{}'::jsonb;
  end if;
  return jsonb_build_object(
    'error',jsonb_build_object(
      'http_code',403,
      'message','NevGenç kaydı yalnızca yetkili öğrenci veya kurum e-posta adresleriyle açılabilir.'
    )
  );
end $$;

grant usage on schema private to supabase_auth_admin;
revoke all on function private.hook_restrict_signup(jsonb) from public,anon,authenticated;
grant execute on function private.hook_restrict_signup(jsonb) to supabase_auth_admin;

-- Auth kayıtlarında profil oluşturma işlemini public SECURITY DEFINER fonksiyondan private şemaya taşı.
create or replace function private.handle_new_user()
returns trigger
language plpgsql security definer set search_path=''
as $$
begin
  insert into public.profiles(id,full_name,email_lower)
  values(
    new.id,
    left(nullif(regexp_replace(coalesce(new.raw_user_meta_data->>'full_name',new.raw_user_meta_data->>'name',''),'\\s+',' ','g'),''),80),
    lower(new.email)
  )
  on conflict(id) do update set email_lower=excluded.email_lower;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert or update of email on auth.users
for each row execute function private.handle_new_user();

