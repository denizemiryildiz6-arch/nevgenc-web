create or replace function private.validate_library_reservation()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
  if new.user_id<>(select auth.uid()) and not private.is_platform_admin((select auth.uid())) then
    raise exception 'Başka kullanıcı adına randevu oluşturamazsın.';
  end if;
  if new.status not in ('confirmed','cancelled','completed') then raise exception 'Geçersiz randevu durumu.'; end if;
  if tg_op='INSERT' and new.status<>'confirmed' then raise exception 'Yeni randevu confirmed durumunda oluşturulmalıdır.'; end if;
  if new.starts_at < now()-interval '5 minutes' then raise exception 'Geçmiş tarih için randevu oluşturulamaz.'; end if;
  if new.starts_at > now()+interval '45 days' then raise exception 'Randevu en fazla 45 gün ileriye alınabilir.'; end if;
  if new.ends_at-new.starts_at < interval '30 minutes' or new.ends_at-new.starts_at > interval '3 hours' then
    raise exception 'Randevu süresi 30 dakika ile 3 saat arasında olmalıdır.';
  end if;
  if not exists(select 1 from public.library_spaces s where s.id=new.space_id and s.is_active=true and s.reservable=true) then
    raise exception 'Bu çalışma alanı rezervasyona açık değil.';
  end if;
  if new.status='confirmed' and exists(
    select 1 from public.library_reservations r
    where r.user_id=new.user_id and r.status='confirmed'
      and r.id<>coalesce(new.id,'00000000-0000-0000-0000-000000000000'::uuid)
      and tstzrange(r.starts_at,r.ends_at,'[)') && tstzrange(new.starts_at,new.ends_at,'[)')
  ) then raise exception 'Bu saat aralığında başka bir randevun bulunuyor.'; end if;
  return new;
end $$;

drop trigger if exists trg_validate_library_reservation on public.library_reservations;
create trigger trg_validate_library_reservation before insert or update on public.library_reservations
for each row execute function private.validate_library_reservation();

