create or replace function private.enforce_platform_admin_limit()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
  perform pg_advisory_xact_lock(hashtextextended('nevgenc-platform-admin-limit',0));
  if (select count(*) from public.platform_admins) >= 4 then
    raise exception 'Platform yöneticisi limiti 4 kişidir.' using errcode='P0001';
  end if;
  return new;
end $$;

drop trigger if exists trg_platform_admin_limit on public.platform_admins;
create trigger trg_platform_admin_limit before insert on public.platform_admins
for each row execute function private.enforce_platform_admin_limit();

create or replace function private.enforce_community_admin_limit()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
  perform pg_advisory_xact_lock(hashtextextended('nevgenc-community-'||new.community_id::text,0));
  if (select count(*) from public.community_admins where community_id=new.community_id) >= 4 then
    raise exception 'Bir toplulukta en fazla 4 yönetici olabilir.' using errcode='P0001';
  end if;
  return new;
end $$;

drop trigger if exists trg_community_admin_limit on public.community_admins;
create trigger trg_community_admin_limit before insert on public.community_admins
for each row execute function private.enforce_community_admin_limit();

