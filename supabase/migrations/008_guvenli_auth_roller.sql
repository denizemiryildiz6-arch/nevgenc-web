create or replace function private.is_platform_admin(p_user_id uuid default auth.uid())
returns boolean
language sql stable security definer set search_path=''
as $$
  select p_user_id is not null
     and exists(select 1 from public.platform_admins p where p.user_id=p_user_id)
$$;

create or replace function private.is_community_admin(p_community_id uuid,p_user_id uuid default auth.uid())
returns boolean
language sql stable security definer set search_path=''
as $$
  select p_user_id is not null and p_community_id is not null
     and exists(select 1 from public.community_admins a where a.community_id=p_community_id and a.user_id=p_user_id)
$$;

create or replace function private.is_organization_editor(p_organization_id uuid,p_user_id uuid default auth.uid())
returns boolean
language sql stable security definer set search_path=''
as $$
  select p_user_id is not null and p_organization_id is not null
     and exists(select 1 from public.organization_editors e where e.organization_id=p_organization_id and e.user_id=p_user_id)
$$;

create or replace function private.is_allowed_app_user(p_user_id uuid default auth.uid())
returns boolean
language plpgsql stable security definer set search_path=''
as $$
declare v_email text;
begin
  if p_user_id is null then return false; end if;
  select lower(email) into v_email from auth.users where id=p_user_id;
  if v_email is null then return false; end if;

  -- SAÜ öğrenci hesabı
  if v_email ~ '^[^@[:space:]]+@ogr\.sakarya\.edu\.tr$' then return true; end if;
  -- SUBÜ öğrenci hesabı (kurumun yayımladığı örnek biçim)
  if v_email ~ '^g[0-9]+@subu\.edu\.tr$' then return true; end if;
  -- Kurum editörü olarak daha sonra rol atanabilecek kurumsal hesaplar
  if v_email ~ '^[^@[:space:]]+@(sakarya\.edu\.tr|serdivan\.bel\.tr)$' then return true; end if;
  if exists(select 1 from public.auth_signup_allowlist a where a.email=v_email) then return true; end if;

  -- Daha önce rol atanmış hesaplar, domain politikası sonradan değişse dahi kilitlenmez.
  if private.is_platform_admin(p_user_id) then return true; end if;
  if exists(select 1 from public.community_admins a where a.user_id=p_user_id) then return true; end if;
  if exists(select 1 from public.organization_editors e where e.user_id=p_user_id) then return true; end if;
  return false;
end $$;

